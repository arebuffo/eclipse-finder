const WINDS = {
  en: ['N', 'NNE', 'NE', 'ENE', 'E', 'ESE', 'SE', 'SSE', 'S', 'SSW', 'SW', 'WSW', 'W', 'WNW', 'NW', 'NNW'],
  es: ['N', 'NNE', 'NE', 'ENE', 'E', 'ESE', 'SE', 'SSE', 'S', 'SSO', 'SO', 'OSO', 'O', 'ONO', 'NO', 'NNO'],
};

let lang = 'en';
try {
  lang = localStorage.getItem('lang')
    || ((navigator.language || 'en').toLowerCase().startsWith('es') ? 'es' : 'en');
} catch { /* default en */ }
if (!STR[lang]) lang = 'en';

export const getLang = () => lang;
export function setLang(l) {
  if (!STR[l]) return;
  lang = l;
  try { localStorage.setItem('lang', l); } catch {}
}
export function t(key, params) {
  let s = STR[lang][key] ?? STR.en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
export const compass = (bearing) => WINDS[lang][Math.round(bearing / 22.5) % 16];
// Percent with locale decimal separator (99.97 → "99,97" in Spanish)
export function fmtPct(pct, decimals) {
  const s = pct.toFixed(decimals);
  return lang === 'es' ? s.replace('.', ',') : s;
}
